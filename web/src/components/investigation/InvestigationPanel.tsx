import { CircleCheck, CircleX, History, ScanSearch, ShieldCheck, TriangleAlert } from 'lucide-react';
import { useMemo } from 'react';
import type { EvidenceItemView, InvestigationDetail, InvestigationSummary } from '@shared/api/contracts';
import { NEXT_STEP_LABELS, POSSIBILITY_LABELS, UNKNOWN_KIND_LABELS } from '@shared/domain/investigation';
import { useInvestigation, useInvestigations, useRunInvestigation } from '../../hooks/useInvestigations';
import { ApiError } from '../../services/apiClient';
import { Badge } from '../ui/Badge';
import { Button } from '../ui/Button';
import { DateTime } from '../ui/DateTime';
import { Panel } from '../ui/Panel';
import { EmptyState, ErrorState, LoadingState } from '../ui/States';
import { EvidenceFields, EvidenceList, EvidenceReference, OriginTag } from './EvidenceReference';

function AiTag() {
  return (
    <span className="rr-origin rr-origin--ai">
      <ScanSearch size={12} aria-hidden="true" />
      AI-generated analysis
    </span>
  );
}

function citedFields(values: { evidenceId: string; field: string }[]): Record<string, string[]> {
  const map: Record<string, string[]> = {};
  for (const v of values) (map[v.evidenceId] ??= []).push(v.field);
  return map;
}

function EvidenceStatus({ changed }: { changed: boolean }) {
  return changed ? (
    <Badge tone="warning" icon={TriangleAlert} size="sm" label="Evidence has changed since this analysis" />
  ) : (
    <Badge tone="success" icon={CircleCheck} size="sm" label="Evidence unchanged since this analysis" />
  );
}

function AttemptMeta({ attempt }: { attempt: InvestigationSummary }) {
  return (
    <dl className="rr-facts rr-facts--compact rr-investigation__meta">
      <div className="rr-facts__item">
        <dt>Model</dt>
        <dd className="rr-mono">{attempt.model}</dd>
      </div>
      <div className="rr-facts__item">
        <dt>Run</dt>
        <dd>
          <DateTime value={attempt.completedAt ?? attempt.requestedAt} />
        </dd>
      </div>
      <div className="rr-facts__item">
        <dt>Evidence items</dt>
        <dd className="rr-num">{attempt.evidenceCount}</dd>
      </div>
      <div className="rr-facts__item">
        <dt>Requested by</dt>
        <dd>{attempt.requestedBy.displayName}</dd>
      </div>
      <div className="rr-facts__item rr-investigation__meta-status">
        <dt>Evidence</dt>
        <dd>
          <EvidenceStatus changed={attempt.evidenceChanged} />
        </dd>
      </div>
    </dl>
  );
}

type Citation = NonNullable<InvestigationDetail['result']>['possibilities'][number]['supports'][number];

function CitationGroup({ heading, citations, evidence }: { heading: string; citations: Citation[]; evidence: Map<string, EvidenceItemView> }) {
  if (citations.length === 0) return null;
  return (
    <div className="rr-ai-citations">
      <p className="rr-ai-citations__heading">{heading}</p>
      <ul className="rr-ai-citations__list">
        {citations.map((c, i) => (
          <li key={i}>
            <span>{c.reason}</span>
            <EvidenceReference id={c.evidenceId} item={evidence.get(c.evidenceId)} cited={[c.field]} />
          </li>
        ))}
      </ul>
    </div>
  );
}

function Analysis({ detail, earlier }: { detail: InvestigationDetail; earlier: boolean }) {
  const evidence = useMemo(() => new Map<string, EvidenceItemView>(detail.evidence.map((e) => [e.id, e])), [detail.evidence]);
  const result = detail.result!;
  const labelFor = new Map<string, string>([
    ...result.known.map((k): [string, string] => [k.id, k.statement]),
    ...result.unknowns.map((u): [string, string] => [u.id, u.question]),
    ...result.possibilities.map((p): [string, string] => [p.id, POSSIBILITY_LABELS[p.category]]),
  ]);

  return (
    <div className="rr-investigation">
      {earlier && <p className="rr-subheading">Most recent analysis that passed the evidence checks</p>}
      <AttemptMeta attempt={detail} />
      <p className="rr-investigation__disclaimer">
        <AiTag />
        <span>
          Generated by an AI model from the evidence snapshot listed below. ReliefRelay checked that every statement cites real evidence and quotes it correctly. It
          cannot check that the reasoning is right. Nothing here changes the case or any payment.
        </span>
      </p>

      <section aria-labelledby="ai-known">
        <h3 id="ai-known" className="rr-subheading">
          What the records show
        </h3>
        <ol role="list" className="rr-ai-list">
          {result.known.map((k) => (
            <li key={k.id} className="rr-ai-item">
              <p className="rr-ai-item__text">{k.statement}</p>
              <EvidenceList ids={k.evidenceIds} evidence={evidence} cited={citedFields(k.citedValues)} />
            </li>
          ))}
        </ol>
      </section>

      <section aria-labelledby="ai-unknowns">
        <h3 id="ai-unknowns" className="rr-subheading">
          What is not known
        </h3>
        {result.unknowns.length === 0 ? (
          <p className="rr-muted">The analysis listed no open questions.</p>
        ) : (
          <ol role="list" className="rr-ai-list">
            {result.unknowns.map((u) => (
              <li key={u.id} className="rr-ai-item">
                <p className="rr-ai-item__kind">{UNKNOWN_KIND_LABELS[u.kind]}</p>
                <p className="rr-ai-item__text">{u.question}</p>
                <EvidenceList ids={u.evidenceIds} evidence={evidence} />
              </li>
            ))}
          </ol>
        )}
      </section>

      <section aria-labelledby="ai-possibilities">
        <h3 id="ai-possibilities" className="rr-subheading">
          Possible explanations
        </h3>
        {result.possibilities.length === 0 ? (
          <p className="rr-muted">The analysis offered no explanation. The records do not support one.</p>
        ) : (
          <>
            <p className="rr-muted rr-ai-note">These are possibilities to check, not conclusions.</p>
            <ol role="list" className="rr-ai-list">
              {result.possibilities.map((p) => (
                <li key={p.id} className="rr-ai-item">
                  <p className="rr-ai-item__kind">Possibility: {POSSIBILITY_LABELS[p.category]}</p>
                  <p className="rr-ai-item__text">{p.explanation}</p>
                  <CitationGroup heading="Consistent with" citations={p.supports} evidence={evidence} />
                  <CitationGroup heading="Weighs against" citations={p.weakens} evidence={evidence} />
                  <p className="rr-ai-item__meta">
                    Would be settled by answering: {p.wouldBeResolvedBy.map((id) => labelFor.get(id) ?? id).join(' · ')}
                  </p>
                </li>
              ))}
            </ol>
          </>
        )}
      </section>

      <section aria-labelledby="ai-steps">
        <h3 id="ai-steps" className="rr-subheading">
          Suggested next steps
        </h3>
        <ol className="rr-ai-list rr-ai-list--numbered">
          {result.nextSteps.map((s) => (
            <li key={s.id} className="rr-ai-item">
              <p className="rr-ai-item__kind">{NEXT_STEP_LABELS[s.type]}</p>
              <p className="rr-ai-item__text">{s.action}</p>
              {s.informationNeeded && <p className="rr-ai-item__meta">Information needed: {s.informationNeeded}</p>}
              {s.requiresHumanAuthorisation && (
                <p className="rr-ai-item__authorisation">
                  <ShieldCheck size={14} aria-hidden="true" />
                  Any payment action needs explicit approval by an authorised person. It cannot be started from this analysis.
                </p>
              )}
              <p className="rr-ai-item__meta">Addresses: {s.relatesTo.map((id) => labelFor.get(id) ?? id).join(' · ')}</p>
            </li>
          ))}
        </ol>
      </section>

      <section aria-labelledby="ai-conclusion">
        <h3 id="ai-conclusion" className="rr-subheading">
          Summary
        </h3>
        <p>{result.conclusion.summary}</p>
        <p className="rr-ai-limitations">
          <strong>What this analysis cannot establish: </strong>
          {result.conclusion.limitations}
        </p>
        <EvidenceList ids={result.conclusion.evidenceIds} evidence={evidence} />
      </section>

      <details className="rr-disclosure">
        <summary>Evidence snapshot sent to the model ({detail.evidence.length} items)</summary>
        <p className="rr-muted">
          Exactly what the model received, assembled by ReliefRelay on <DateTime value={detail.evidenceAsOf} />. Withheld from the model: {detail.withheld.join(', ')}.
        </p>
        <ul className="rr-evidence-snapshot">
          {detail.evidence.map((item) => (
            <li key={item.id}>
              <p className="rr-evidence-snapshot__title">
                <span className="rr-mono">{item.id}</span> <OriginTag origin={item.origin} />
              </p>
              <EvidenceFields item={item} />
            </li>
          ))}
        </ul>
      </details>
    </div>
  );
}

function AttemptStatus({ attempt }: { attempt: InvestigationSummary }) {
  if (attempt.status === 'succeeded') return <Badge tone="success" icon={CircleCheck} size="sm" label="Passed evidence checks" />;
  if (attempt.status === 'pending') return <Badge tone="progress" icon={History} size="sm" label="In progress" />;
  return <Badge tone="critical" icon={CircleX} size="sm" label={attempt.failure?.label ?? 'Failed'} />;
}

function FailedAttempt({ attempt, issues }: { attempt: InvestigationSummary; issues?: InvestigationDetail['validationIssues'] }) {
  return (
    <div className="rr-notice rr-notice--warning" role="status">
      <TriangleAlert size={16} aria-hidden="true" />
      <div>
        <p>
          <strong>The most recent attempt failed: {attempt.failure?.label}.</strong> {attempt.failure?.description} {attempt.failure?.detail}
        </p>
        <p className="rr-muted">The rejected analysis is neither shown nor stored. No case or payment data was changed.</p>
        {issues && issues.length > 0 && (
          <details className="rr-disclosure">
            <summary>Failed checks ({issues.length})</summary>
            <ul className="rr-plain-list">
              {issues.map((issue, i) => (
                <li key={i}>
                  {issue.message} <span className="rr-mono rr-muted">({issue.code})</span>
                </li>
              ))}
            </ul>
          </details>
        )}
      </div>
    </div>
  );
}

function AttemptHistory({ attempts }: { attempts: InvestigationSummary[] }) {
  if (attempts.length === 0) return null;
  return (
    <details className="rr-disclosure">
      <summary>All attempts ({attempts.length})</summary>
      <ol role="list" className="rr-history">
        {attempts.map((a) => (
          <li key={a.id} className="rr-history__item">
            <p>
              <AttemptStatus attempt={a} />
            </p>
            <p className="rr-activity__meta">
              <DateTime value={a.requestedAt} />
              <span>{a.requestedBy.displayName}</span>
              <span className="rr-mono">{a.model}</span>
              <span>{a.evidenceCount} evidence items</span>
              {a.evidenceChanged && <span>evidence since changed</span>}
            </p>
          </li>
        ))}
      </ol>
    </details>
  );
}

export function InvestigationPanel({ caseId, caseVersion }: { caseId: string; caseVersion: number }) {
  const { data, error, isPending, isError, refetch, isFetching } = useInvestigations(caseId);
  const run = useRunInvestigation(caseId);
  const latestAttempt = data?.investigations[0];
  const latestFailed = latestAttempt && latestAttempt.status === 'failed' ? latestAttempt : null;
  const failedDetail = useInvestigation(caseId, latestFailed?.failure?.code === 'failed_validation' ? latestFailed.id : null);

  const action = data?.availability.configured ? (
    <Button
      variant="secondary"
      size="sm"
      icon={<ScanSearch size={16} aria-hidden="true" />}
      loading={run.isPending}
      disabled={!data.availability.canRun}
      onClick={() => run.mutate(caseVersion)}
    >
      {data.latestSucceeded ? 'Run again' : 'Run investigation'}
    </Button>
  ) : undefined;

  return (
    <Panel
      title="AI-assisted investigation"
      description="An AI model reviews a minimised snapshot of this case’s records and lists what they show, what is unknown and what to check next. It never decides, approves or changes anything."
      actions={action}
      className="rr-investigation-panel"
    >
      {isPending && <LoadingState label="Loading investigations" rows={2} />}
      {isError && <ErrorState title="Investigations could not be loaded" error={error} onRetry={() => void refetch()} retrying={isFetching} />}
      {data && !data.availability.configured && (
        <EmptyState icon={ScanSearch} title="AI-assisted investigation is not configured">
          No OpenAI API key is set on the server, so no case data is sent anywhere. The rest of this case works normally.
        </EmptyState>
      )}
      {data && data.availability.configured && (
        <>
          {!data.availability.canRun && data.availability.reason && !run.isPending && <p className="rr-muted rr-investigation__reason">{data.availability.reason}</p>}
          <div aria-live="polite" role="status" className="rr-investigation__live">
            {run.isPending && (
              <p className="rr-investigation__running">
                Investigation running. This can take up to a minute. The attempt is saved even if you leave this page.
              </p>
            )}
          </div>
          {run.isError && (
            <p className="rr-inline-error" role="alert">
              {run.error.message}
              {run.error instanceof ApiError && run.error.status === 409 && ' The latest details have been loaded.'}
            </p>
          )}
          {latestFailed && !run.isPending && <FailedAttempt attempt={latestFailed} issues={failedDetail.data?.validationIssues} />}
          {data.latestSucceeded ? (
            <Analysis detail={data.latestSucceeded} earlier={latestAttempt?.id !== data.latestSucceeded.id} />
          ) : (
            !run.isPending &&
            data.availability.canRun && (
              <EmptyState icon={ScanSearch} title="No analysis yet">
                Running an investigation sends a minimised snapshot of this case to {data.availability.model}: references, amounts, statuses, dates, error codes and
                findings. Names, contact details, recipient references, notes and file contents are never sent.
              </EmptyState>
            )
          )}
          <p className="rr-muted rr-investigation__usage">
            {data.availability.usedToday} of {data.availability.dailyLimit} investigations used by your organisation today.
          </p>
          <AttemptHistory attempts={data.investigations} />
        </>
      )}
    </Panel>
  );
}
